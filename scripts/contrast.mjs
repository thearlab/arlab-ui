// WCAG 2.2 contrast check of every text/surface and UI/surface pair the components use, in the four
// palettes (light, dark) x (magenta, violet). Reads src/tokens/tokens.css, writes docs/CONTRAST.md,
// and fails when a pair is under its minimum. Run: npm run check:contrast
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { contrast, mix } from '../src/lib/color.ts';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const css = fs.readFileSync(path.join(root, 'src/tokens/tokens.css'), 'utf8').replace(/\/\*[\s\S]*?\*\//g, '');
const block = (sel) => {
  const i = css.indexOf(sel + ' {');
  if (i < 0) throw new Error('tokens.css: no block ' + sel);
  const body = css.slice(i + sel.length + 2, css.indexOf('}', i));
  return Object.fromEntries([...body.matchAll(/--([\w-]+):\s*(#[0-9a-fA-F]{6})/g)].map((m) => [m[1], m[2]]));
};
const light = block(':root');
const palettes = {
  'Light, magenta (default)': light,
  'Light, violet': { ...light, ...block(':root[data-accent="violet"]') },
  'Dark, magenta (default)': { ...light, ...block(':root[data-theme="dark"]') },
  'Dark, violet': { ...light, ...block(':root[data-theme="dark"]'), ...block(':root[data-theme="dark"][data-accent="violet"]') },
};
const T = 4.5, U = 3;
const surfaces = ['bg', 'frame', 'surface', 'sunken'];
const pairs = [
  ...['ink', 'ink-2', 'ink-3'].flatMap((f) => surfaces.map((b) => [f, b, T, 'Text'])),
  ['ink', 'sunken-2', T, 'Text on a pressed fill'],
  ...['surface', 'frame', 'accent-soft', 'accent-soft-2'].map((b) => ['accent-text', b, T, 'Accent text, active item']),
  ['ink', 'accent-soft', T, 'Text on the selected row'],
  ...['accent', 'accent-hover', 'accent-press'].map((b) => ['on-accent', b, T, 'Primary button label']),
  ['on-bad', 'bad', T, 'Danger button label'],
  ...['ok', 'warn', 'bad', 'info'].flatMap((s) => [[s, s + '-soft', T, 'Status tag'], [s, 'surface', T, 'Status text on a card'], [s, 'frame', T, 'Status text on the page']]),
  ...surfaces.map((b) => ['control-line', b, U, 'Control edge (input, checkbox, switch)']),
  ...surfaces.map((b) => ['focus', b, U, 'Focus ring']),
  ...['surface', 'frame'].map((b) => ['accent', b, U, 'Selected marker, switch on, slider fill']),
  ...[1, 2, 3, 4, 5, 6, 7, 8].map((n) => ['#FFFFFF', 'hue-' + n, U, 'Initials on an avatar (bold)']),
  ...['ok', 'warn', 'bad', 'info'].map((s) => [s, 'surface', U, 'Status dot']),
];
let fails = 0;
const lines = ['# Contrast', '', 'Generated by `npm run check:contrast` from `src/tokens/tokens.css`. WCAG 2.2 AA: 4.5:1 for text, 3:1 for large or bold text and for UI parts (control edges, focus rings, status dots, selected markers). Every pair a component uses is listed; the build fails when one is under its minimum.', ''];
for (const [name, p] of Object.entries(palettes)) {
  lines.push(`## ${name}`, '', '| Use | Foreground | Background | Ratio | Needs | |', '|---|---|---|---|---|---|');
  for (const [f, b, min, use] of pairs) {
    const fg = f.startsWith('#') ? f : p[f], bg = p[b];
    if (!fg || !bg) throw new Error(`missing token ${!fg ? f : b} in ${name}`);
    const r = contrast(fg, bg), ok = r >= min;
    if (!ok) { fails++; console.error(`FAIL ${name}: ${f} on ${b} = ${r.toFixed(2)} (needs ${min})`); }
    lines.push(`| ${use} | \`${f}\` ${fg} | \`${b}\` ${bg} | ${r.toFixed(2)} | ${min} | ${ok ? 'pass' : '**FAIL**'} |`);
  }
  lines.push('');
}
void mix;
fs.writeFileSync(path.join(root, 'docs/CONTRAST.md'), lines.join('\n'));
console.log(fails ? `contrast: ${fails} pair(s) under the minimum` : `contrast: ok (${pairs.length} pairs x ${Object.keys(palettes).length} palettes)`);
process.exit(fails ? 1 : 0);
